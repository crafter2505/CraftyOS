void idt_set_entry(int vector, void (*handler)(void), uint8_t type_attr) {
    uint64_t addr = (uint64_t)handler;

    idt[vector].offset_low  = addr & 0xFFFF;
    idt[vector].selector    = 0x10;
    idt[vector].ist         = 0;
    idt[vector].type_attr   = type_attr;
    idt[vector].offset_mid  = (addr >> 16) & 0xFFFF;
    idt[vector].offset_high = (addr >> 32) & 0xFFFFFFFF;
    idt[vector].reserved    = 0;
}

void idt_init(void) {
    unsigned char *raw = (unsigned char *)idt;
    for (unsigned int i = 0; i < sizeof(idt); i++) {
        raw[i] = 0;
    }

    for (int i = 0; i < 256; i++) {
        idt_set_entry(i, isr_stubs[i], 0x8E);
    }

    idt_desc.size = sizeof(idt) - 1;
    idt_desc.address = (uint64_t)&idt;

    __asm__ volatile ("lidt %0" : : "m"(idt_desc));
}